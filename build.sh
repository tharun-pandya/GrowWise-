#!/usr/bin/env bash
# ==============================================================================
# GrowWise - Render Unified Build Script
# Builds React + TypeScript + Vite frontend and sets up Python FastAPI backend
# for single-service deployment under one public URL.
# ==============================================================================

set -e

echo "=========================================================="
echo "🌱 GrowWise: Starting Unified Single-Service Build"
echo "=========================================================="

echo "--> Step 1: Installing frontend dependencies and building Vite app..."
npm install || npm install --legacy-peer-deps
npm run build

echo "--> Step 2: Verifying compiled frontend assets in dist/..."
if [ ! -f "dist/index.html" ]; then
  echo "❌ Error: dist/index.html was not generated by Vite build!"
  exit 1
fi
echo "✓ Verified: dist/index.html and dist/assets/ are ready for FastAPI."

echo "--> Step 3: Installing Python backend dependencies..."
if command -v pip >/dev/null 2>&1; then
  pip install -r backend/requirements.txt
elif python3 -c "import pip" >/dev/null 2>&1; then
  python3 -m pip install -r backend/requirements.txt
else
  echo "ℹ️ Note: pip not found in local container; on Render, pip is preinstalled and installs backend/requirements.txt automatically."
fi

echo "--> Step 4: Running automated test suite..."
python3 -m unittest backend/tests/test_backend.py tests/test_knowledge_base.py tests/test_rules.py tests/test_ai_engine.py -v

echo "=========================================================="
echo "🎉 Build completed successfully!"
echo "FastAPI will now serve both the React app and API at runtime."
echo "=========================================================="
